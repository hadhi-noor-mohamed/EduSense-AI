import { FlaskConical } from 'lucide-react'
import { cn } from '../../utils/cn'

/**
 * Academic transparency chip — reminds viewers that predictions in this
 * build come from a mock, browser-side scoring service.
 */
export function MockBadge({
  className,
  compact,
}: {
  className?: string
  compact?: boolean
}) {
  return (
    <span
      className={cn(
        'inline-flex items-center gap-1.5 rounded-md border border-dashed border-brand-400/60 bg-brand-50/70 px-2 py-1 text-[10.5px] font-semibold text-brand-700 dark:border-brand-400/40 dark:bg-brand-500/10 dark:text-brand-300',
        className,
      )}
      title="Predictions are produced by a deterministic mock service in this prototype, not a trained model."
    >
      <FlaskConical className="h-3 w-3" aria-hidden />
      {compact ? 'Demo prediction' : 'Prototype prediction · mock ML service'}
    </span>
  )
}

export function PrototypeNote({ className }: { className?: string }) {
  return (
    <p
      className={cn(
        'rounded-xl border border-dashed border-line bg-panel-muted px-3.5 py-2.5 text-[12px] leading-relaxed text-ink-subtle',
        className,
      )}
    >
      <strong className="font-semibold text-ink-muted">Prototype notice:</strong> risk scores,
      factor contributions and recommendations on this page are generated by a transparent mock
      ML service running in the browser. The interface matches the planned{' '}
      <code className="rounded bg-panel px-1 py-0.5 text-[11px] text-accent">POST /api/predict</code>{' '}
      contract so a trained model + SHAP backend can be connected later without UI changes.
    </p>
  )
}
